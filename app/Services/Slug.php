<?php

declare(strict_types=1);

namespace Pafish\Services;

/** Shared slug normalization and collision suffixing for all content types. */
final class Slug
{
    /** Generate a normalized slug, using pinyin transliteration when intl is available. */
    public static function slugify(string $input): string
    {
        $source = trim($input);
        if (class_exists(\Transliterator::class)) {
            $transliterator = \Transliterator::create('Any-Latin; Latin-ASCII; Lower()');
            if ($transliterator !== null) {
                $source = $transliterator->transliterate($source);
            }
        }
        $slug = self::normalize($source);
        return $slug !== '' ? $slug : 'post-' . date('YmdHis') . '-' . bin2hex(random_bytes(3));
    }

    /** Normalize user supplied slugs using the same rules as title-derived slugs. */
    public static function normalize(string $input): string
    {
        $s = mb_strtolower(trim($input), 'UTF-8');
        $s = (string) preg_replace('/\s+/u', '-', $s);
        $s = (string) preg_replace('/[^\p{L}\p{N}_-]/u', '', $s);
        $s = (string) preg_replace('/-+/u', '-', $s);
        return trim($s, '-');
    }

    /** New automatic slugs get a collision suffix; manual values fail clearly on conflict. */
    public static function forSave(?string $submitted, string $title, ?string $existing, callable $occupied, bool $autoGenerated = false, int $maxLength = 255): string
    {
        if ($existing !== null && ($submitted === null || trim((string) $submitted) === $existing)) {
            $slug = $existing;
            $automatic = false;
        } elseif (trim((string) $submitted) === '' && $existing !== null && !$autoGenerated) {
            $slug = $existing;
            $automatic = false;
        } elseif ($autoGenerated) {
            // Automatic UI previews are best-effort; regenerate from the title on
            // the server so Chinese titles always use the same pinyin result.
            $slug = self::slugify($title);
            $automatic = true;
        } elseif (trim((string) $submitted) === '') {
            $slug = self::slugify($title);
            $automatic = true;
        } else {
            $slug = self::normalize((string) $submitted);
            $automatic = $autoGenerated;
        }
        if ($slug === '') throw new \RuntimeException('别名只能包含字母、数字、中文、下划线和连字符');
        if ($automatic) return self::resolveUniqueWithinLength($slug, $occupied, $maxLength);
        if ($occupied($slug)) throw new \RuntimeException('别名已被使用，请更换或留空自动生成');
        return $slug;
    }

    public static function resolveUniqueWithinLength(string $slug, callable $check, int $maxLength, int $maxAttempts = 50): string
    {
        $slug = mb_substr($slug, 0, $maxLength, 'UTF-8');
        if (!$check($slug)) return $slug;
        for ($i = 2; $i <= $maxAttempts + 1; $i++) {
            $suffix = '-' . $i;
            $base = rtrim(mb_substr($slug, 0, max(1, $maxLength - mb_strlen($suffix, 'UTF-8')), 'UTF-8'), '-');
            $candidate = $base . $suffix;
            if (!$check($candidate)) return $candidate;
        }
        throw new \RuntimeException('无法生成可用的别名，请手动指定其他别名');
    }

    /**
     * 唯一别名：不冲突直接返回；冲突依次尝试 {slug}-2、{slug}-3 …（最多 50 次）
     * @param callable(string): bool $check 返回 true 表示已被占用
     */
    public static function resolveUnique(string $slug, callable $check, int $maxAttempts = 50): string
    {
        $candidate = $slug;
        for ($i = 2; $i <= $maxAttempts; $i++) {
            if (!$check($candidate)) {
                return $candidate;
            }
            $candidate = $slug . '-' . $i;
        }
        if (!$check($candidate)) {
            return $candidate;
        }
        throw new \RuntimeException('无法生成可用的别名，请手动指定其他别名');
    }
}
